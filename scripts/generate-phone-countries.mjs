import { getCountries, getCountryCallingCode } from "libphonenumber-js/max";
import { mkdir, copyFile, writeFile, readFile } from "node:fs/promises";
const names = new Intl.DisplayNames(["es"], { type: "region" });
const countries = getCountries()
  .map((code) => ({
    code,
    name: names.of(code),
    dialCode: `+${getCountryCallingCode(code)}`,
  }))
  .sort((a, b) =>
    a.code === "ES"
      ? -1
      : b.code === "ES"
        ? 1
        : a.name.localeCompare(b.name, "es"),
  );
await mkdir("public/flags", { recursive: true });
for (const country of countries)
  await copyFile(
    `node_modules/country-flag-icons/3x2/${country.code}.svg`,
    `public/flags/${country.code}.svg`,
  );
await writeFile(
  "public/flags/LICENSE.txt",
  (await readFile("node_modules/country-flag-icons/LICENSE", "utf8")).replace(
    /\r\n/g,
    "\n",
  ),
);
await writeFile(
  "lib/phone-countries.ts",
  `// Generated by scripts/generate-phone-countries.mjs. Flags: country-flag-icons (MIT).\nimport type { CountryCode } from "libphonenumber-js/max";\nexport const phoneCountries: ReadonlyArray<{code: CountryCode; name: string; dialCode: string}> = ${JSON.stringify(countries, null, 2)};\n`,
);
console.log(
  `Generated ${countries.length} country options and locally served flags.`,
);
